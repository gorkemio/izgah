/**
 * Künye colour tokens from one source (docs/designs/izgah-ui-v4.md §1, §11).
 *
 * tokens/kunye.json → three generated stylesheets, committed so izgah.com keeps no build step and
 * the extension package stays self-contained:
 *
 *   src/lib/styles/palette.css        web app: palette slots resolved by light-dark() in tokens.css
 *   extensions/src/styles/palette.css browser extensions: semantic --color-* via media queries
 *   site/palette.css                  izgah.com: the same semantic names via media queries
 *
 * Run `pnpm tokens` after editing the JSON; tests/unit/tokens-sync.test.ts compares the files with a
 * fresh render, and tests/unit/tokens-contrast.test.ts checks every palette for WCAG contrast.
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

export type Scheme = 'light' | 'dark';
export type PaletteName = 'default' | 'contrast';
export type Palette = Record<string, string>;

export interface KunyeTokens {
	palettes: Record<Scheme, Record<PaletteName, Palette>>;
	accent: Record<Scheme, Palette>;
}

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..');
export const SOURCE = 'tokens/kunye.json';

export const OUTPUTS = {
	app: 'src/lib/styles/palette.css',
	extension: 'extensions/src/styles/palette.css',
	site: 'site/palette.css'
} as const;

export function readTokens(root = ROOT): KunyeTokens {
	return JSON.parse(fs.readFileSync(path.join(root, SOURCE), 'utf8')) as KunyeTokens;
}

const HEADER = (purpose: string) =>
	[
		'/*',
		` * ${purpose}`,
		` * Generated by scripts/tokens/build.ts from ${SOURCE}. Do not edit by hand: change the JSON`,
		' * and run `pnpm tokens`.',
		' */'
	].join('\n');

function declarations(prefix: string, palette: Palette, indent: string): string[] {
	return Object.entries(palette).map(([role, value]) => `${indent}--${prefix}${role}: ${value};`);
}

function rule(selectors: string[], lines: string[], indent: string): string {
	return [`${indent}${selectors.join(`,\n${indent}`)} {`, ...lines, `${indent}}`].join('\n');
}

/** Web app: per-scheme palette slots (--light-*, --dark-*) that tokens.css maps with light-dark(). */
export function renderAppPalette(tokens: KunyeTokens): string {
	const inner = '\t\t';
	const blocks: string[] = [];
	for (const scheme of ['light', 'dark'] as const) {
		for (const name of ['default', 'contrast'] as const) {
			const selectors =
				name === 'default'
					? [':root', `[data-${scheme}-theme='default']`]
					: [`[data-${scheme}-theme='contrast']`];
			blocks.push(
				rule(selectors, declarations(`${scheme}-`, tokens.palettes[scheme][name], inner), '\t')
			);
		}
	}
	const accent: string[] = [];
	for (const scheme of ['light', 'dark'] as const) {
		const values = tokens.accent[scheme];
		accent.push(
			`${inner}--accent-${scheme}: var(--${scheme}-link);`,
			`${inner}--on-accent-${scheme}: ${values['on-accent']};`,
			`${inner}--accent-soft-${scheme}: ${values['accent-soft']};`,
			`${inner}--accent-text-${scheme}: var(--${scheme}-link);`,
			`${inner}--accent-border-${scheme}: ${values['accent-border']};`
		);
	}
	blocks.push(rule([':root', '.theme-preview'], accent, '\t'));
	return [
		HEADER('Künye palettes for the web app: light and dark, standard and high contrast.'),
		'@layer tokens {',
		blocks.join('\n\n'),
		'}',
		''
	].join('\n');
}

/** Extension and site: semantic --color-* names switched by prefers-color-scheme / -contrast. */
export function renderStandalonePalette(tokens: KunyeTokens, purpose: string): string {
	const semantic = (scheme: Scheme, name: PaletteName, indent: string) => {
		const accent = tokens.accent[scheme];
		const link = tokens.palettes[scheme][name].link;
		return [
			...declarations('color-', tokens.palettes[scheme][name], indent).filter(
				(line) => !line.includes('--color-shadow-lg')
			),
			`${indent}--color-accent: ${link};`,
			`${indent}--color-accent-text: ${link};`,
			`${indent}--color-on-accent: ${accent['on-accent']};`,
			`${indent}--color-accent-soft: ${accent['accent-soft']};`,
			`${indent}--color-accent-border: ${accent['accent-border']};`,
			`${indent}--shadow-lg: ${tokens.palettes[scheme][name]['shadow-lg']};`
		];
	};
	const media = (query: string, scheme: Scheme, name: PaletteName) =>
		[`@media ${query} {`, rule([':root'], semantic(scheme, name, '\t\t'), '\t'), '}'].join('\n');
	return [
		HEADER(purpose),
		rule([':root'], semantic('light', 'default', '\t'), ''),
		'',
		media('(prefers-color-scheme: dark)', 'dark', 'default'),
		'',
		media('(prefers-contrast: more)', 'light', 'contrast'),
		'',
		media('(prefers-contrast: more) and (prefers-color-scheme: dark)', 'dark', 'contrast'),
		''
	].join('\n');
}

export function renderAll(tokens: KunyeTokens): Record<keyof typeof OUTPUTS, string> {
	return {
		app: renderAppPalette(tokens),
		extension: renderStandalonePalette(
			tokens,
			'Künye palettes for the browser extensions: they follow the system theme and contrast.'
		),
		site: renderStandalonePalette(
			tokens,
			'Künye palettes for izgah.com: it follows the system theme and contrast.'
		)
	};
}

function main(): void {
	const rendered = renderAll(readTokens());
	for (const [key, file] of Object.entries(OUTPUTS) as [keyof typeof OUTPUTS, string][]) {
		fs.writeFileSync(path.join(ROOT, file), rendered[key]);
		console.log(`wrote ${file}`);
	}
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
	main();
}
